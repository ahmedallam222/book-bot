// CACHE WARMING — يحمّل كتب مشابهة في الخلفية
// ══════════════════════════════════════════════

export async function warmRelatedCache(bookName: string): Promise<void> {
  try {
    const normalized = normalizeArabic(bookName.toLowerCase());

    // ابحث عن التصنيف المناسب
    let relatedBooks: string[] = [];
    for (const [keys, books] of Object.entries(GENRE_MAP)) {
      const keyList = keys.split("|");
      const match = books.some(b =>
        normalizeArabic(b.toLowerCase()).includes(normalized) ||
        normalized.includes(normalizeArabic(b.toLowerCase()))
      );
      if (match) {
        relatedBooks = books.filter(b =>
          normalizeArabic(b.toLowerCase()) !== normalized
        );
        break;
      }
    }

    if (relatedBooks.length === 0) return;

    // اختر 3 كتب عشوائية من نفس التصنيف وسخّن الكاش
    const picks = relatedBooks
      .sort(() => Math.random() - 0.5)
      .slice(0, 3);

    for (const book of picks) {
      try {
        // Skip queries that already have a recent cache entry (HIT *or* MISS).
        // Previously this used `if (!cached)` against `getSearchCacheResults`,
        // which always returns an array — `!cached` was always false and the
        // warming branch never ran. With `hasRecentSearchCache` we honour both
        // the 1h positive TTL and the 5min negative TTL so we don't burn
        // Firecrawl budget re-checking known-negative queries.
        if (await hasRecentSearchCache(book)) continue;
        await searchAllSources(book);
        L.info("suggestions", `Warmed cache for: ${book.slice(0, 50)}`);
      } catch {}
    }
  } catch (e) {
    L.warn("suggestions", `warmRelatedCache error: ${String(e).slice(0, 80)}`);
  }
}
