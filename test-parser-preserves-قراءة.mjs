let pass = 0, fail = 0;
const failures = [];

for (const t of TESTS) {
  const got = await parseBookName(t.in);
  const want = t.out;
  const ok = got === want;
  if (ok) {
    pass++;
    console.log(`PASS  ${t.why} :: "${t.in}" → "${got}"`);
  } else {
    fail++;
    failures.push({ ...t, got });
    console.log(`FAIL  ${t.why} :: "${t.in}"`);
    console.log(`        want: "${want}"`);
    console.log(`        got:  "${got}"`);
  }
}

console.log("");
console.log("=".repeat(60));
console.log(`RESULTS: ${pass} PASS, ${fail} FAIL  (total ${TESTS.length})`);
console.log("=".repeat(60));

if (fail > 0) {
  console.log("");
  console.log("Failures:");
  for (const f of failures) {
    console.log(` - ${f.why}: in="${f.in}" want="${f.out}" got="${f.got}"`);
  }
  process.exit(1);
}
process.exit(0);
